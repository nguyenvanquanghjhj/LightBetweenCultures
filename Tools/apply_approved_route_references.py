def remove_drafting_spurs(points):
    # Shared corridors may meet before a named drafting anchor. Erase the
    # out-and-back spur, not the fixed edge arrivals or a runtime graph link.
    clean=[]
    for point in points:
        previous=next((i for i,p in enumerate(clean) if math.dist(p,point)<.8),None)
        if previous is not None:clean=clean[:previous+1]
        else:clean.append(point)
    while len(clean)>2:
        removed=False
        for i in range(1,len(clean)-1):
            a,b,c=clean[i-1:i+2];u=(b[0]-a[0],b[1]-a[1]);v=(c[0]-b[0],c[1]-b[1]);lu,lv=math.hypot(*u),math.hypot(*v)
            if lu*lv and sum(x*y for x,y in zip(u,v))/(lu*lv)<-.95 and min(lu,lv)<55:
                clean.pop(i);removed=True;break
        if not removed:break
    return clean

class Draft:
    def __init__(self,city):
        self.city=city;self.points={n['id']:pixel(n['arrivalPosition'] if n.get('hasArrivalPosition') else n['position']) for n in city['nodes']};self.links={};self.polylines=[]
    def road(self,a,b,*via):
        def endpoint(name):
            if isinstance(name,tuple):
                key='p'+','.join(map(str,name));self.points[key]=name;return key
            return name
        a,b=endpoint(a),endpoint(b)
        pts=[self.points[a],*via,self.points[b]]
        self.polylines.append(dict(start=a,end=b,pixels=pts))
        length=sum(math.dist(p,q) for p,q in zip(pts,pts[1:]))
        self.links.setdefault(a,[]).append((b,length,pts));self.links.setdefault(b,[]).append((a,length,list(reversed(pts))))
    def route(self,a,b):
        todo=[(0,a,[])];best={a:0}
        while todo:
            cost,at,route=heapq.heappop(todo)
            if cost>best[at]+1e-6:continue
            if at==b:return route
            for nxt,length,pts in self.links.get(at,[]):
                value=cost+length
                if value<best.get(nxt,float('inf')):
                    best[nxt]=value;heapq.heappush(todo,(value,nxt,route+pts[bool(route):]))
        raise ValueError('Unconnected drafting anchor '+a+' '+b)

